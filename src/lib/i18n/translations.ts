export type Language = 'bn' | 'en';

export const BENGALI_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBengaliDigits(input: string | number | undefined | null): string {
  if (input === undefined || input === null) return '';
  return String(input).replace(/[0-9]/g, (d) => BENGALI_DIGITS[+d] || d);
}

export function formatCurrency(
  amount: number | undefined | null,
  lang: Language = 'bn',
  useBengaliDigits: boolean = false
): string {
  const safeAmount = Number(amount) || 0;
  const formatted = new Intl.NumberFormat('en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(safeAmount);

  if (lang === 'bn') {
    return useBengaliDigits ? `৳ ${toBengaliDigits(formatted)}` : `৳ ${formatted}`;
  }
  return `৳ ${formatted}`;
}

export function formatNumber(
  num: number | string | undefined | null,
  lang: Language = 'bn',
  useBengaliDigits: boolean = false
): string {
  if (num === undefined || num === null) return '';
  const str = String(num);
  if (lang === 'bn' && useBengaliDigits) {
    return toBengaliDigits(str);
  }
  return str;
}

